public class Tema02_Ejercicio09 {
    final static double PI = 3.1415f;

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        double radio = 3.55f;
        double longitud;
        
        longitud = radio * PI * 2f;
        
        System.out.println("La longitud de una circunferencia cuyo radio vale "
                + radio + " sería igual a: " + longitud);
    }
    
}
